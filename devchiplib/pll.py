"""rPLL parameter search and wrapper generation for the GW2A-18C (27 MHz input).

Gowin rPLL (GW2A datasheet):
    CLKOUT = FCLKIN * (FBDIV_SEL + 1) / (IDIV_SEL + 1)
    VCO    = CLKOUT * ODIV_SEL        must be 500 .. 1250 MHz
    PFD    = FCLKIN / (IDIV_SEL + 1)  must be >= 3 MHz
    IDIV_SEL, FBDIV_SEL in 0..63; ODIV_SEL in {2,4,8,...,128}
    CLKOUT range 3.90625 .. 625 MHz
"""
FCLKIN = 27.0
ODIVS = (2, 4, 8, 16, 32, 48, 64, 80, 96, 112, 128)
VCO_MIN, VCO_MAX = 500.0, 1250.0
PFD_MIN = 3.0
OUT_MIN, OUT_MAX = 3.90625, 625.0


class PllError(Exception):
    pass


def solve(target_mhz, fclkin=FCLKIN):
    if not (OUT_MIN <= target_mhz <= OUT_MAX):
        raise PllError(f"{target_mhz} MHz is outside the rPLL range {OUT_MIN}..{OUT_MAX} MHz")
    best = None
    for idiv in range(64):
        pfd = fclkin / (idiv + 1)
        if pfd < PFD_MIN:
            break
        for fbdiv in range(64):
            out = pfd * (fbdiv + 1)
            if not (OUT_MIN <= out <= OUT_MAX):
                continue
            for odiv in ODIVS:
                vco = out * odiv
                if VCO_MIN <= vco <= VCO_MAX:
                    err = abs(out - target_mhz)
                    # prefer exact, then higher PFD (less jitter), then mid-range VCO
                    key = (round(err, 9), -pfd, abs(vco - 875.0))
                    if best is None or key < best[0]:
                        best = (key, {"IDIV_SEL": idiv, "FBDIV_SEL": fbdiv, "ODIV_SEL": odiv,
                                      "out_mhz": out, "vco_mhz": vco, "pfd_mhz": pfd})
    if best is None:
        raise PllError(f"no valid rPLL setting for {target_mhz} MHz")
    return best[1]


def wrapper(name, p, fclkin=FCLKIN):
    fin = f"{fclkin:g}"
    return f"""// {name}.v - generated by `devchip.py pll`
// {fin} MHz in -> {p['out_mhz']:.6f} MHz out   (VCO {p['vco_mhz']:.1f} MHz, PFD {p['pfd_mhz']:.3f} MHz)
// `lock` goes high once the output is stable; hold your logic in reset until then.
module {name} (
    input  wire clkin,      // connect the 27 MHz board clock (port `clk`)
    output wire clkout,
    output wire lock
);
    rPLL #(
        .FCLKIN("{fin}"),
        .IDIV_SEL({p['IDIV_SEL']}),
        .FBDIV_SEL({p['FBDIV_SEL']}),
        .ODIV_SEL({p['ODIV_SEL']}),
        .DYN_IDIV_SEL("false"), .DYN_FBDIV_SEL("false"), .DYN_ODIV_SEL("false"),
        .DYN_SDIV_SEL(2),
        .PSDA_SEL("0000"), .DYN_DA_EN("false"), .DUTYDA_SEL("1000"),
        .CLKOUT_FT_DIR(1'b1), .CLKOUTP_FT_DIR(1'b1),
        .CLKOUT_DLY_STEP(0), .CLKOUTP_DLY_STEP(0),
        .CLKFB_SEL("internal"),
        .CLKOUT_BYPASS("false"), .CLKOUTP_BYPASS("false"), .CLKOUTD_BYPASS("false"),
        .CLKOUTD_SRC("CLKOUT"), .CLKOUTD3_SRC("CLKOUT"),
        .DEVICE("GW2A-18C")
    ) u_pll (
        .CLKOUT(clkout), .LOCK(lock), .CLKOUTP(), .CLKOUTD(), .CLKOUTD3(),
        .RESET(1'b0), .RESET_P(1'b0), .CLKIN(clkin), .CLKFB(1'b0),
        .FBDSEL(6'b0), .IDSEL(6'b0), .ODSEL(6'b0), .PSDA(4'b0), .DUTYDA(4'b0), .FDLY(4'b0)
    );
endmodule
"""
